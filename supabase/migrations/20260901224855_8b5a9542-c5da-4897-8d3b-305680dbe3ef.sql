## THC Concentrate Addiction FAQ

### Is dabbing more dangerous than smoking marijuana?

In terms of dependence risk and mental health effects, yes. Dabbing delivers a much larger dose of THC much faster, raising the risk of tolerance, dependence, anxiety, and in some people temporary psychosis. It also uses extreme heat, which can produce lung-irritating byproducts.

### How long does withdrawal from THC concentrates last?

Most symptoms peak within three to seven days and ease over two to three weeks. Sleep problems and irritability linger longest, sometimes a month or more. Withdrawal is uncomfortable but generally not dangerous, though anyone with a serious mental health history should stop under medical supervision.

### My child says delta-8 is legal, so it must be safe. Is that true?

Legal and safe are two different things. Many hemp-derived products, including delta-8, are inconsistently regulated and tested, so potency and purity vary package to package. Legality tells you about the law, not about what the product does to a developing brain.

### Should we do an intervention for marijuana or THC concentrates?

If use is causing serious damage to health, school, work, or safety, and repeated conversations haven't changed anything, an intervention is a reasonable next step. The substance matters less than the trajectory. A professional interventionist helps the family prepare, set boundaries, and arrange treatment in advance.

### What if my loved one refuses treatment?

You still have moves. You can change what you fund, what you tolerate in your home, and what you participate in. Get your own support through family coaching or a group like Al-Anon. Many people accept help only after the family stops absorbing the consequences.

