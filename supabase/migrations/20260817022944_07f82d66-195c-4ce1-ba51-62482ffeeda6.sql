## Frequently Asked Questions

### Do grandparents need legal custody to raise their grandchildren?

Not always, but it helps. Without legal standing you may struggle to enroll a child in school, consent to medical care, or add them to insurance. Options range from informal kinship care to guardianship to full custody, depending on your state. Talk with a family law attorney or legal aid office early.

### Is financial help available for grandparents raising grandchildren?

Yes, and it is widely underused. Depending on your state you may qualify for kinship care payments, child-only TANF, SNAP, Medicaid for the children, and subsidized childcare. Many do not require formal custody. Your state's kinship navigator program can walk you through it.

### Should I let my grandchildren see their parent while they are still using?

Supervised contact is usually better than no contact, as long as the parent is not intoxicated and the child wants to go. Children who lose all contact often fill the gap with fantasy or self-blame. You set the terms: your location, your timing, your call on when it ends.

### How do I take care of myself when everyone depends on me?

Start with one non-negotiable thing that belongs only to you: a support group, a walk, a therapist. Grandparent caregiver groups exist in most areas and connect you with people who understand without needing it explained. If you go down, the whole arrangement goes with you.

### Can an intervention work if my adult child has already been to treatment?

Yes. Multiple treatment episodes are common and not a sign of failure. Addiction is chronic, and many people need more than one attempt before recovery holds. What usually changes the outcome is a better-matched level of care, a stronger aftercare plan, and a family that has stopped sending mixed signals.

