$post$If you are a grandparent raising grandchildren because of addiction, you did not plan for this. You planned for weekends and birthdays and spoiling them a little and sending them home. Instead you are packing lunches at sixty-two and lying awake wondering where your adult child is tonight.

You are not alone. Grandparents raising grandchildren because of addiction now number in the hundreds of thousands. About 2.4 million children in the United States are raised primarily by grandparents or other relatives, and substance use is one of the leading reasons. That will not make your house quieter at 2 a.m., but it means there is a well-worn path here.

This is for the grandparent carrying two griefs at once: the child in the next room who needs you, and the adult child still out there using.

## Why Are So Many Grandparents Raising Grandchildren Because of Addiction?

Grandparents step in because someone has to, and because they are usually the only ones close enough to see it happening. When a parent's substance use escalates, the home becomes unpredictable long before anyone calls it a crisis. The grandparent is often the first adult to notice the kids are hungry, missing school, or scared — one of the clearest examples of <a href="/blog/how-addiction-affects-siblings-family-guide">how addiction affects children in the home</a>.

The handoff rarely happens in one dramatic moment. It happens in stages:

- A weekend stay that turns into a month.
- A late-night call after an arrest, an overdose, or an eviction.
- A caseworker asking whether you can take the children today.

By the time you realize you are the primary parent again, you have been doing the job for a while. Many grandparents carry guilt about "taking" the children when they simply responded to a vacuum they did not create.

## What Are the Hidden Costs Grandparents Carry?

The financial strain gets talked about most, but the heaviest cost is usually grief nobody acknowledges, because everyone around you is busy praising you for stepping up.

### Grief with no funeral

Your adult child is alive but not present. No service, no casserole, no card. Clinicians call this ambiguous loss, and it is uniquely hard because it never resolves into something you can mourn and move past.

### Financial pressure at the wrong stage of life

Retirement savings built over thirty years can go to childcare, legal fees, braces, and a bigger car. Help exists and often goes unused. Look into kinship care assistance in your state, available in many cases even without formal custody.

### Exhaustion

Parenting is a young body's job. Doing it while grieving and fielding calls at all hours would wear out anyone. Burnout here is not weakness. It is arithmetic.

## How Do You Talk to Your Grandchildren About Their Parent's Addiction?

Tell them the truth in an age-appropriate way, and tell them clearly that none of this is their fault. Children who are not given honest information do not stop wondering. They fill the silence with a story, and the story they invent is almost always that they caused it.

1. Use simple, non-shaming language: "Your mom has a sickness called addiction. It makes her brain want a drug more than anything else."
2. Separate the person from the behavior. A child can hold both "my dad loves me" and "my dad is not safe to live with right now."
3. Never make them the messenger. Do not send a child to plead, deliver an ultimatum, or report back.
4. Answer the question they asked. If a nine-year-old asks "Is Mom coming to my game?" she wants a yes or no, not a lecture.
5. Say the fault sentence out loud, more than once: "You did not cause this. You cannot fix it. And you are not going anywhere."

Consider a group built for kids, like Alateen, or a school counselor who knows the situation. Children in these homes become small adults fast, and one place where they get to be a kid matters.

## How Do You Set Boundaries With Your Adult Child?

The clearest boundary is built around the children's safety, and it works best when it is specific, calm, and consistent. Vague boundaries invite negotiation. Specific ones describe reality. If you have never done this formally, start with the basics of <a href="/blog/how-to-set-boundaries-addicted-loved-one">how to set boundaries with an addicted loved one</a>.

- Visits happen when your adult child is sober, at a time and place you choose, and you decide when they end.
- Money goes to the children, not the parent. Groceries, clothing, school fees. Never cash.
- Consequences get stated once and followed, without a speech: "You showed up high, so today's visit is over. Call me tomorrow."
- Your door stays open to recovery and closed to using. That is not rejection. It is the only honest position you can hold while children live in your house.

Here is the part few people say out loud: taking the grandchildren often removes the last consequence your adult child was facing. You did the right thing for the kids and also made it easier for their parent to keep going. Both are true.

