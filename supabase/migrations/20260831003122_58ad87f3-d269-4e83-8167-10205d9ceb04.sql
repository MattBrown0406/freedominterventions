$MD$# How to Choose a Rehab: 12 Questions Every Family Should Ask

*By Matt Brown | Freedom Interventions | August 30, 2026*

You finally heard the word you have been praying for. Your loved one said yes. Maybe it came after an intervention, after an overdose scare, after a night you never want to relive. And now, instead of relief, you are sitting in front of a screen at two in the morning trying to figure out how to choose a rehab from a thousand websites that all look the same.

Every one of them shows a sunset. Every one of them promises hope. Every one of them has a phone number somebody answers immediately. And you are supposed to make one of the most important decisions of your family's life while you are exhausted, scared, and working against a window of willingness that could close by morning.

Take a breath. You do not need to become an expert on addiction treatment tonight. You need to know what actually matters, what to ask, and what to walk away from. That is what this guide gives you.

## How Do You Choose a Rehab?

To choose a rehab, start with the level of care your loved one clinically needs, then verify the program's licensing and accreditation, then confirm it treats mental health alongside addiction and includes the family. Cost and location matter, but they come after clinical fit. The right program is the one that matches the severity of the problem, not the one with the nicest photos.

Here is something most families do not know: a lot of the marketing you see online is not run by the treatment centers themselves. Some of it is run by third-party call centers paid to route your call somewhere. That is why the same handful of facilities keep showing up in different colors. Once you know what to ask, that noise gets a lot quieter.

## What Level of Care Does Your Loved One Actually Need?

Level of care means how much structure and medical supervision a person needs. Choosing the wrong level is one of the most common reasons a first attempt at treatment falls apart. Someone who needs medical detox does not belong in a weekly outpatient group, and someone eight months sober does not need a hospital unit.

The common levels, from most to least structured:

- **Medical detox:** three to ten days of supervised withdrawal, often necessary for alcohol, benzodiazepines, and opioids.
- **Residential or inpatient:** thirty to ninety days living onsite with 24-hour support and daily clinical work.
- **Partial hospitalization (PHP):** treatment most of the day, five days a week, while living in sober housing.
- **Intensive outpatient (IOP):** roughly nine to fifteen hours a week, which allows work or school.
- **Outpatient and aftercare:** weekly therapy, medication management, and peer support.

A good program performs an assessment before it tells you what your loved one needs. If a facility recommends its own highest-priced level of care before anyone has asked a single clinical question, that tells you something important about how they operate. Our guide to <a href="/treatment-planning">matching a loved one to the right level of care</a> walks through this in more detail.

## 12 Questions to Ask Before You Say Yes

Ask these on the first call and write the answers down. Any legitimate program will answer them without hesitation, and the ones that dodge will tell you everything you need to know.

1. Are you licensed by the state, and are you accredited by the Joint Commission or CARF?
2. Am I speaking with the facility directly, or with a call center?
3. Who does the clinical assessment, and when does it happen?
4. Do you treat co-occurring mental health conditions like depression, anxiety, trauma, or bipolar disorder onsite?
5. Do you have a psychiatrist and nursing staff, and how often will my loved one see them?
6. What is your staff-to-client ratio, and how many hours of individual therapy come each week?
7. Do you offer medication-assisted treatment, and what is your position on it?
8. What does your family program look like, and when do we participate?
9. What happens on discharge day, and who builds the aftercare plan?
10. What exactly does the cost cover, what will insurance pay, and what will we owe?
11. What is your policy if my loved one relapses or wants to leave early?
12. Can I speak with a family who has been through your program?

Question eight matters more than most families realize. Addiction is a family illness. Programs that treat the individual in isolation send a changed person home to an unchanged system. When the family does its own work, outcomes improve.

## What Are the Red Flags of a Bad Treatment Center?

The clearest red flags are aggressive sales pressure, offers of free travel or waived costs, guaranteed success rates, and refusal to discuss money in plain terms. Reputable programs inform you. Predatory ones close you.

Watch for these specifically:

- **A free plane ticket or an offer to waive your deductible.** This is often patient brokering, and it is illegal in many states.
- **Guarantees.** No ethical clinician promises a success rate, because no one can.
- **Urgency scripts.** "We have one bed left today" is a sales tactic. Real availability is a fact they will simply tell you.
- **Vague clinical answers.** If they cannot name their therapies or their medical staff, keep dialing.
- **No aftercare plan.** A program that ends at the front door is selling a vacation, not treatment.

You are allowed to hang up. You are allowed to call three places and compare. Willingness is precious, and that is real, but a rushed decision into the wrong facility usually costs far more time than one extra day of research.

## How Do You Know a Program Is the Right Fit?

The right fit is a program that treats the whole person, includes the family, and plans for the day after discharge. Beyond credentials, look for specific experience with your loved one's substance, age group, and circumstances.

A few practical fit questions worth weighing:

- **Distance:** leaving town can create healthy separation from using friends, while staying close makes family participation easier. Neither is automatically better.
- **Population:** a program that mostly serves twenty-two-year-olds may not fit a fifty-five-year-old professional, and the reverse is also true.
- **Trauma-informed care:** if trauma is part of the story, ask which trained approaches they use.
- **Length of stay:** thirty days is a start, not a finish. Ask what the recommended continuum of care looks like after that.

And here is something worth holding onto. The perfect facility does not exist. Treatment is not the cure. Treatment is the interruption that makes recovery possible. What happens in the twelve months after discharge determines far more than any brochure ever will — which is why <a href="/aftercare-guidance">aftercare planning</a> deserves as much attention as admission day.

