## What Are Nitazenes?

Nitazenes are a family of synthetic opioids developed in a lab in the 1950s as potential painkillers but never approved for medical use because they were too dangerous. They have resurfaced in the illegal drug supply over the last several years. Some nitazenes are estimated to be as strong as or stronger than fentanyl, which is already roughly 50 times stronger than heroin.

You may see names like isotonitazene ("iso"), metonitazene, protonitazene, or etonitazene. Families do not need to memorize these. What matters is that they all suppress breathing, and they are all being mixed into drugs without the buyer's knowledge.

Nitazenes have been found in counterfeit oxycodone and Percocet pills, in heroin, in fentanyl, and even in fake Xanax. Your loved one may have no idea they are taking one. That is the part that keeps me up at night when I am working with a family. If you are already dealing with pills or powder in your home, our guide to [fentanyl addiction help for families](/blog/fentanyl-addiction-help-for-families) covers the same territory from another angle.

## Why Are Nitazenes So Dangerous?

Nitazenes are dangerous because of three things working together: extreme potency, unpredictable dosing, and the fact that they can be hard to detect. A dose the size of a few grains of salt can stop someone's breathing, and the person taking it usually does not know it is there.

- **Potency is not consistent.** Different nitazenes vary widely in strength, and street drugs are mixed by hand. Two pills from the same bag can carry very different risk.
- **Standard drug tests often miss them.** Many routine urine screens and many fentanyl test strips do not detect nitazenes. A "clean" test does not mean a safe supply.
- **Overdoses can require more naloxone.** Narcan still works, but reversing a nitazene overdose may take multiple doses, and the person can slip back into overdose after waking up.
- **Tolerance offers less protection.** Someone who has used opioids for years can still overdose the first time nitazenes show up in their supply.

This is not a reason to panic. It is a reason to act.

## What Are the Warning Signs of Nitazene Addiction?

The warning signs of nitazene addiction look like opioid addiction in general, because that is what it is. Watch for pinpoint pupils, nodding off mid-sentence, slowed breathing, slurred speech, and cycles of sickness (sweating, vomiting, restlessness) that clear up suddenly after they "go out for a bit."

Beyond the physical signs, pay attention to the pattern of the person's life:

- Money disappearing, items missing, or unexplained requests for cash
- New friends you never meet and phone calls taken in another room
- Pulling away from family, hobbies, and responsibilities they used to care about
- Small baggies, foil, straws, or pills that are not in a pharmacy bottle

If you find pills that look like prescription medication but did not come from a pharmacy, treat them as if they contain fentanyl or nitazenes. Do not taste or handle them loosely, and keep them away from children and pets.

## How Do I Recognize and Respond to a Nitazene Overdose?

A nitazene overdose looks like any opioid overdose: the person is unresponsive, breathing is very slow or has stopped, lips or fingertips turn blue or gray, and they may make a gurgling or snoring sound. Call 911 immediately, give naloxone, and keep giving additional doses every two to three minutes until they respond or help arrives.

Practical steps every family should take today:

1. Keep naloxone (Narcan) in your home, your car, and your bag. It is available over the counter at most pharmacies.
2. Learn how to use it before you need it. Practice with the box in your hand so your hands know what to do when your mind is racing.
3. Stay with the person after naloxone. Nitazenes can outlast it, and breathing can stop again.
4. Know your state's Good Samaritan law. In most states, you and the person overdosing are protected from certain charges when you call for help.

Naloxone is not a treatment plan. It is a way to keep someone alive long enough to get one. I tell families that all the time, and I mean both halves of the sentence.

