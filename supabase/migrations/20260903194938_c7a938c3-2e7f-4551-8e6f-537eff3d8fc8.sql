## Frequently Asked Questions About Nitazene Addiction

### What are nitazenes and how are they different from fentanyl?

Nitazenes are a class of synthetic opioids that were never approved for medical use. Like fentanyl, they are extremely potent and are mixed into street drugs. Some are estimated to be stronger than fentanyl, and they may not show up on fentanyl test strips or standard drug screens.

### Does Narcan work on a nitazene overdose?

Yes. Naloxone works on nitazenes because they act on the same opioid receptors. However, reversal may require multiple doses, and the person can re-overdose after the naloxone wears off. Always call 911 and stay with the person.

### Can you tell if a pill has nitazenes in it?

Not by looking. Counterfeit pills are made to look identical to real prescription medication, and standard fentanyl test strips often do not detect nitazenes. The safest assumption is that any pill not from a pharmacy could contain a deadly opioid.

### What are the signs someone is addicted to nitazenes?

The signs mirror opioid addiction: pinpoint pupils, nodding off, slowed breathing, cycles of withdrawal sickness, missing money, secrecy, and pulling away from family. Because nitazenes are usually hidden in other drugs, the person may believe they are addicted to something else.

### Is nitazene addiction treatable?

Yes. Nitazene addiction is treated like other opioid use disorders, with medically supervised detox, medications such as buprenorphine or methadone when appropriate, and ongoing treatment and support. Many people who used fentanyl and nitazenes are living in long-term recovery today.$md$,
