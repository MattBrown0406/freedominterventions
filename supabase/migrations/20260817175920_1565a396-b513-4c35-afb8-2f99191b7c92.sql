## Frequently Asked Questions

### Why does my addicted child steal from family instead of strangers?

Family is the lowest-risk target. Strangers and employers involve police and prosecution, while families tend to absorb the loss to avoid conflict. Over time, this teaches the addiction that home is the safest place to take from — usually without anyone intending to send that message.

### Should I confront my family member about stealing?

Yes, but do it once, calmly, and after you've gathered facts and secured your valuables. Bring specifics rather than accusations, state what's changing going forward, and don't expect a confession. The goal is clarity for you, not a confession from them.

### How do I protect my elderly parent from an addicted relative?

Freeze your parent's credit, remove the relative's account access and power of attorney if applicable, set up transaction alerts, and consider adding a trusted second signer. If significant money is already gone, contact adult protective services and an elder law attorney — financial exploitation of a senior is a crime in every state.

### Is it enabling to give money to an addicted family member?

Giving cash to someone in active addiction almost always funds the addiction, regardless of the stated reason. Paying a specific bill directly or buying a needed item is a reasonable middle ground. The clearest test: does this help them get better, or does it help them stay comfortable where they are?

### Will an intervention work if my loved one is already stealing?

Often, yes. Theft usually means consequences are mounting, and mounting consequences are exactly what make a well-planned intervention effective. Most people who accept treatment at an intervention do so reluctantly — willingness tends to come later, after the fog clears.

