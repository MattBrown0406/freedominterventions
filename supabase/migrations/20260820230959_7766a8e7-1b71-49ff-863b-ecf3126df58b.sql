Families rarely get this right alone, and that is not a failure of love. You are too close, too tired, and too frightened to see the whole board. A structured <a href="/what-is-an-intervention">family intervention</a> gives you what late-night arguments never will: one message, one plan, one door held open, and boundaries the whole family holds together.

Whatever you decide about the bedroom down the hall, decide it on purpose. People recover from this. Families come back from this — not because someone found the perfect answer, but because somebody finally stopped negotiating with the chaos and started leading.

## Frequently Asked Questions

### Is letting my addicted son or daughter live with me enabling?

Not by itself. Housing becomes enabling when it is bundled with cash, covered consequences, and no expectations. A room with written conditions, a treatment requirement, and no cash supports a person rather than funding an addiction. The address is not the issue — the terms are.

### Can I legally make an addicted family member leave my home?

It depends on your state and how long they have lived there. In many states, an adult living in a home for an extended period may have tenant rights requiring formal eviction, even without a lease. Before setting a move-out date, call a local attorney or legal aid office.

### What if they have nowhere to go?

This fear keeps families frozen for years, and it deserves a real answer. Do the legwork first: identify detox facilities, treatment programs, sober living homes, and shelters near you, and know what beds are available. Then you are not putting someone on the street — you are offering a specific alternative and letting them choose.

### What if my spouse and I disagree about whether they can stay?

Do not decide until you are aligned. A split household guarantees the rules will not hold — your loved one will simply go to whichever parent says yes. If you cannot get on the same page alone, bring in an interventionist or family counselor to build one plan you can both stand behind.

