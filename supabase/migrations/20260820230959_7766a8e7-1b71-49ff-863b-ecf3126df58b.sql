$post$If you are lying awake wondering whether your addicted loved one should keep living in your home, you are not a bad parent, spouse, or sibling. You are caught between two fears that both feel unbearable. If they stay, your home keeps absorbing the chaos. If they go, you are terrified of what happens to them out there.

No decision removes all the risk. But there is a way to make this one with clear eyes instead of panic. I have sat in living rooms with hundreds of families facing this question. The ones who do best are not the ones who make the "right" call — they are the ones who make a deliberate call, in writing, with terms everyone understands.

## Is It Wrong to Let an Addicted Loved One Live in Your Home?

No. Letting an addicted loved one live in your home is not automatically enabling, and asking them to leave is not automatically tough love. What matters is not where they sleep. What matters is whether their living situation makes the addiction easier or harder to continue.

"Enabling" gets thrown around so casually it has lost its meaning. <a href="/blog/enabling-loved-one-addiction">Enabling a loved one with addiction</a> is not kindness — it is any action that removes the natural consequence of the drinking or using, so the person never feels the weight of it.

A bed in your house is neutral. What surrounds that bed is not. Free housing plus cash, a car, the phone bill, and calling their boss when they cannot get up adds up to a life where using costs almost nothing. So the honest question is not "should they live here?" It is "what is my home currently paying for?"

## What Should You Ask Yourself Before Deciding?

Get specific first. Vague fears lead to vague decisions that collapse on the first hard night. Answer these honestly, on paper.

- **Is anyone in this house unsafe?** Small children, elderly parents, or someone in their own early recovery change the math immediately.
- **Has there been theft, violence, or a threat of it?** Not "could there be" — has there been?
- **Are drugs being used or stored in the home?** Are people coming and going that you did not invite?
- **What am I actually providing?** Write the real list: rent, food, phone, insurance, gas, cash.
- **What have I already tried, and what actually changed?** Use dates and outcomes, not impressions.

If you answered yes to any safety question, that answers the housing question for you. Safety is not a boundary you negotiate. Everything else is a conversation about terms.

## What House Rules Should You Set If They Stay?

If your addicted loved one stays, the arrangement needs written conditions and a review date. Verbal understandings collapse under pressure, because addiction is very good at renegotiating in the moment. Cover five things:

1. **No use in the home.** No substances on the property, no dealing, no unknown visitors. This one is not flexible.
2. **A specific treatment step with a date.** Not "get help soon" — an assessment scheduled by Friday, a detox bed accepted, an intake kept.
3. **Financial terms.** What you will and will not pay for. Most families should stop giving cash entirely and pay providers directly instead.
4. **Contribution to the household.** Work, school, treatment, chores — something. Adults who contribute nothing disappear into the fog.
5. **A review date.** Thirty days is reasonable. Put it on the calendar and keep it.

Write it down and both sign it. When the argument comes at 11 p.m. — and it will — you are pointing at a page instead of relying on willpower. If you have never put limits in writing before, start with <a href="/blog/how-to-set-boundaries-addicted-loved-one">how to set boundaries with an addicted loved one</a>. And decide in advance what happens if a rule is broken. A rule with no stated consequence is a wish.

## When Is It Time to Ask an Addicted Loved One to Leave?

It is time to change the living situation when your home has stopped being a place of safety and become part of the machinery of the addiction. You do not need a catastrophe to justify acting. These are the signs I take seriously:

- Anyone in the home is afraid — especially a child.
- Drugs are being used or stored in the house despite clear agreements.
- Strangers are coming and going and you do not know who they are.
- Money, medication, or belongings keep going missing, or you are locking your own bedroom door.
- The agreement keeps getting broken and nothing on your end has changed.

That last one deserves a hard look. If you have set the same limit five times and never once held it, your loved one has learned something reliable: your words do not carry weight. That is not a character flaw. It is what love under exhaustion looks like. But it has to change before anything else can.

## How Do You Ask Someone to Leave Without Abandoning Them?

Asking an addicted loved one to leave does not mean cutting them off. Done well, it separates two things that never should have been fused: your home and your love. You can withdraw one and keep the other fully intact. Here is how:

1. **Pick the time deliberately.** Sober hours, daylight, never mid-argument.
2. **Have another adult present** — not to gang up, but to keep it steady.
3. **Lead with love and be brief.** "I love you. I am not willing to keep providing a place where this can continue. Here is what I will do."
4. **Offer a door, not just an exit.** Have a real option ready — a detox bed, an intake appointment, a sober living referral. Make help easier to say yes to than the street.
5. **State the date and hold it.** The follow-through is the entire message.
6. **Say what stays open** — calls, meals, rides to treatment. Name it out loud so they hear the difference between losing the room and losing you.

You will feel like the villain doing this. Feeling like the villain is not evidence that you are one. Guilt is a feeling, not a verdict.

