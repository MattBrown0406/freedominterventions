$MD$# How Long Should Rehab Be? A Family's Guide to 30, 60, and 90-Day Treatment

*By Matt Brown | Freedom Interventions | August 26, 2026*

Your loved one finally said yes. After months — maybe years — of fear, arguing, and sleepless nights, they agreed to go to treatment. And now the admissions counselor is asking a question you have no idea how to answer: how long should rehab be?

If you are trying to decide between a 30-day, 60-day, or 90-day program, here is the short version: longer is almost always better. Research consistently shows that outcomes improve when someone stays in treatment at least 90 days. But the honest answer is more complicated than a number, and you deserve to understand why before you sign anything.

Let's walk through it together.

## How Long Should Rehab Be? What the Research Actually Says

Most addiction research points to the same conclusion: 90 days is the threshold where outcomes meaningfully improve. The National Institute on Drug Abuse has long held that treatment lasting less than 90 days is of limited effectiveness, and that longer durations are associated with better long-term results.

That does not mean 90 days must all happen inside one residential facility. It means 90 days of continuous, connected care — which might look like 30 days residential, followed by 30 days in a partial hospitalization program, followed by outpatient treatment and sober living. Understanding your <a href="/treatment-planning">addiction treatment options</a> early makes that sequencing far easier to build.

Here is why time matters so much. Addiction is not just a behavior problem. It changes how the brain handles reward, stress, and impulse control. Those systems do not reset in a week. Depending on the substance, the brain fog, mood swings, and cravings of early recovery — sometimes called <a href="/blog/paws-post-acute-withdrawal-syndrome-family-guide">post-acute withdrawal</a> — can last months.

Thirty days is often just enough time for someone to stop feeling terrible. Ninety days is enough time for them to start building something.

## What Does a 30-Day Rehab Program Actually Do?

A 30-day program stabilizes someone. It gets substances out of their body, manages withdrawal safely, and introduces them to the basics of recovery. That is genuinely valuable — but it is a starting line, not a finish line.

Thirty days is the most common length for one simple reason: it is what insurance most readily covers. It became a standard because of billing cycles, not because of brain science.

A 30-day program may be a reasonable fit when:

- The substance use is caught relatively early and has not yet caused major life collapse.
- There is no serious co-occurring mental health condition like bipolar disorder or severe trauma.
- The person has stable housing, employment, and a supportive environment to return to.
- There is a strong, fully-arranged aftercare plan already in place before discharge.

Here is what I want families to hear clearly: if your loved one completes 30 days and comes home to the same apartment, the same friends, and the same routine — with no next step scheduled — the odds are not in their favor. That is not a character failure. It is a math problem.

## When Is 60 or 90-Day Treatment the Better Choice?

Longer treatment makes sense when addiction has been going on for years, when there is a mental health condition running alongside it, or when the person has been through treatment before and relapsed. In those situations, 30 days rarely gets past the surface.

Sixty and 90-day programs give someone time to move from crisis mode into actual work — trauma processing, psychiatric stabilization, family repair, relapse prevention skills, and practicing sober living in real time rather than in theory.

### Signs Your Loved One Likely Needs More Than 30 Days

- They have completed treatment before and returned to use.
- They are dealing with depression, anxiety, PTSD, or another diagnosed mental health condition alongside the addiction.
- The substance involved is one with a long withdrawal tail — alcohol, benzodiazepines, opioids, or methamphetamine.
- They have no stable, sober living environment to return to.
- Their use has been daily and heavy for more than a year.
- There are legal issues, medical complications, or a history of overdose.

If two or more of those apply, push for longer care. I know that is hard to hear when you are exhausted and want your person home. But bringing someone home early is one of the most common regrets I hear from families.

## What About the Cost and Insurance Reality?

Longer treatment costs more, and most insurance plans will not simply approve 90 days upfront. What usually happens instead is that facilities request authorization in increments, and coverage continues as long as medical necessity is documented. If you are weighing networks, our guide to <a href="/blog/in-network-vs-out-of-network-rehab">in-network versus out-of-network rehab</a> explains the trade-offs.

This is where families have more leverage than they realize. A few practical steps:

1. Ask the facility directly: "What is your average length of stay for someone with this history?" A good program will answer honestly rather than sell you a package.
2. Ask who handles insurance authorization and how often they appeal denials. Appeals succeed more often than people expect.
3. Ask what the step-down plan is — partial hospitalization, intensive outpatient, sober living — and whether those are covered.
4. Ask about scholarships, sliding scale rates, or extended-care rates. Many facilities have them and do not advertise them.

And consider the other side of the ledger. Repeated 30-day stays, emergency room visits, lost jobs, legal fees, and property damage add up to far more than one longer stay. Paying once for adequate treatment is usually cheaper than paying four times for inadequate treatment.

## How Do You Talk to Your Loved One About Staying Longer?

Most people entering treatment want the shortest stay possible. That is normal, and it is not defiance — it is fear. Thirty days feels survivable. Ninety days feels like a sentence.

The conversation goes better when you lead with the outcome they want rather than the outcome you want. Try something closer to:

"I know you want your life back. I want that too. What I have learned is that the people who get it back and keep it are usually the ones who gave it enough time. I'd rather you be gone longer once than gone over and over."

Then stop talking. Let it sit. You are not negotiating a contract — you are planting a reason.

It also helps to set the expectation before admission, not after. Families who agree in advance that the plan is 90 days of continuous care have a much easier time when the resistance shows up in week three. And it will show up in week three. That is the part where the fog lifts, the discomfort is real, and the mind starts making a very persuasive case for coming home.

## The Question Behind the Question

When families ask me how long rehab should be, they are usually asking something underneath it: how long until I can stop being afraid?

I wish I could give you a date. What I can tell you, after 23 years of my own sobriety and two decades of walking families through this, is that recovery is not a length of stay. It is a direction. Treatment is where it starts, not where it finishes.

The families who do best are the ones who stop thinking in terms of "getting them fixed" and start thinking in terms of building a structure that holds — for their loved one and for themselves. Longer treatment buys time for that structure to get built.

You do not have to figure this out alone, and you do not have to get every decision perfect. You just have to make the next right one.

## Frequently Asked Questions About Rehab Length

### How long should rehab be for alcohol addiction?
For alcohol addiction, most clinicians recommend a minimum of 30 days residential care followed by continued outpatient treatment, with 90 days of total connected care as the target. Alcohol withdrawal can be medically dangerous and often requires supervised detox first. Long-term heavy drinking also affects sleep, mood, and thinking for months, so shorter stays frequently end before the person feels stable.

### Is 30-day rehab long enough?
For some people it is, but for most it is a starting point rather than a complete course of treatment. Thirty days can stabilize someone and introduce recovery skills, but research shows outcomes improve significantly with 90 days or more of continuous care. If a 30-day program is what is available, treat it as phase one and have the next phase scheduled before discharge.

### Can someone leave rehab early?
Yes. In almost all cases, treatment is voluntary and an adult can leave against medical advice at any time. This is why the pre-treatment conversation about length matters so much, and why many families use a <a href="/interventionist">professional interventionist</a> to establish clear agreements and consequences ahead of time. If your loved one is threatening to leave, contact the treatment team immediately rather than negotiating alone.

### Does insurance cover 90-day rehab?
Most insurance plans do not authorize 90 days upfront, but many will cover extended care in increments when medical necessity is documented and reauthorized. Coverage often continues through step-down levels of care such as partial hospitalization and intensive outpatient. Ask the facility's utilization review team how they handle authorizations and appeals before you assume the answer is no.

### What happens after rehab ends?
The transition out of treatment is one of the highest-risk periods in recovery, which is why <a href="/aftercare-guidance">aftercare planning</a> should begin during treatment, not at discharge. A strong plan usually includes outpatient therapy, a support group, a sponsor or recovery coach, psychiatric follow-up if needed, and often sober living. Families should have their own support in place as well.

### Is longer rehab always better?
Longer is generally better, but quality and fit matter too. A well-matched 60-day program with strong clinical care and real aftercare planning will usually outperform a 90-day program that is poorly run or does not address a co-occurring mental health condition. Length is one important factor among several, not a guarantee on its own.

